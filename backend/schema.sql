-- MarketHub PostgreSQL schema. Applied by: python -m backend.init_db

CREATE TABLE IF NOT EXISTS accounts (
    id VARCHAR(80) PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    type VARCHAR(10) NOT NULL,
    password_hash VARCHAR(200) NOT NULL,
    code VARCHAR(32),
    referred_by VARCHAR(80) REFERENCES accounts(id) ON DELETE SET NULL,
    avatar TEXT NOT NULL DEFAULT '',
    status VARCHAR(10) NOT NULL DEFAULT 'active'
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_accounts_email ON accounts (email);
CREATE UNIQUE INDEX IF NOT EXISTS ix_accounts_code ON accounts (code);

CREATE TABLE IF NOT EXISTS auth_sessions (
    token_hash VARCHAR(64) PRIMARY KEY,
    account_id VARCHAR(80) NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS ix_auth_sessions_account_id ON auth_sessions (account_id);

CREATE TABLE IF NOT EXISTS categories (
    name VARCHAR(40) PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS products (
    id VARCHAR(100) PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    category VARCHAR(40) NOT NULL REFERENCES categories(name) ON UPDATE CASCADE,
    price INTEGER NOT NULL,
    stock INTEGER NOT NULL,
    seller_id VARCHAR(80) NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    image TEXT NOT NULL DEFAULT 'product-placeholder.svg',
    tag VARCHAR(40) NOT NULL DEFAULT 'New'
);
CREATE INDEX IF NOT EXISTS ix_products_seller_id ON products (seller_id);

CREATE TABLE IF NOT EXISTS cart_lines (
    account_id VARCHAR(80) NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    product_id VARCHAR(100) NOT NULL,
    quantity INTEGER NOT NULL,
    PRIMARY KEY (account_id, product_id)
);

CREATE TABLE IF NOT EXISTS orders (
    id VARCHAR(40) PRIMARY KEY,
    buyer_id VARCHAR(80) NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    seller_id VARCHAR(80) NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    buyer VARCHAR(100) NOT NULL,
    buyer_email VARCHAR(254) NOT NULL,
    buyer_phone VARCHAR(30) NOT NULL,
    pickup_area VARCHAR(160) NOT NULL,
    total INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    ordered_at TIMESTAMPTZ NOT NULL,
    payment_method VARCHAR(30) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_orders_buyer_id ON orders (buyer_id);
CREATE INDEX IF NOT EXISTS ix_orders_seller_id ON orders (seller_id);

CREATE TABLE IF NOT EXISTS order_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(40) NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_id VARCHAR(100) NOT NULL,
    name VARCHAR(120) NOT NULL,
    price INTEGER NOT NULL,
    quantity INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_order_items_order_id ON order_items (order_id);

CREATE TABLE IF NOT EXISTS installments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(40) NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    label VARCHAR(40) NOT NULL,
    amount INTEGER NOT NULL,
    due_at TIMESTAMPTZ NOT NULL,
    paid BOOLEAN NOT NULL DEFAULT FALSE,
    paid_at TIMESTAMPTZ,
    method VARCHAR(40)
);
CREATE INDEX IF NOT EXISTS ix_installments_order_id ON installments (order_id);

CREATE TABLE IF NOT EXISTS live_sessions (
    id VARCHAR(100) PRIMARY KEY,
    seller_id VARCHAR(80) NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    platform VARCHAR(40) NOT NULL,
    product_ids TEXT NOT NULL DEFAULT '[]',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    started_at TIMESTAMPTZ NOT NULL,
    ended_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_live_sessions_seller_id ON live_sessions (seller_id);
